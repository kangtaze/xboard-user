<h2>3. 信息使用</h2>
<p>我们收集的信息用于以下目的：</p>
<ul>
<li><strong>提供和改善服务：</strong>账户管理、连接服务、节点分配、故障排查</li>
<li><strong>安全与防滥用：</strong>检测异常登录、防止 DDoS 攻击、阻止违规使用</li>
<li><strong>计费与客服：</strong>处理付款、管理订阅、响应客户咨询</li>
<li><strong>服务优化：</strong>分析使用趋势、优化节点部署、提升连接质量</li>
</ul>
<p>我们不会将您的信息用于未经披露的目的，也不会将您的个人信息出售给第三方。</p>

