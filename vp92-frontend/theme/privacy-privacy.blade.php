<h2>5. 数据存储与安全</h2>
<h3>5.1 数据存储</h3>
<ul>
<li>用户账户数据存储在我们位于香港的服务器上</li>
<li>VPN 连接日志存储在 Cloudflare Workers 边缘节点，30 天后自动删除</li>
<li>支付信息由第三方支付平台（如 Stripe、支付宝）安全处理，我们不直接存储信用卡或银行卡信息</li>
</ul>
<h3>5.2 安全措施</h3>
<ul>
<li>所有数据传输使用 TLS 1.3 加密</li>
<li>VPN 连接使用 WireGuard / Shadowsocks / VMess 等加密协议</li>
<li>密码使用 bcrypt 哈希存储，不可逆加密</li>
<li>数据库定期备份，采用加密存储</li>
<li>服务器部署防火墙、入侵检测系统</li>
<li>员工访问用户数据需经过严格权限审批</li>
</ul>

<h2>6. 数据共享</h2>
<p>我们不会出售您的个人信息。在以下有限情况下，我们可能共享您的数据：</p>
<ul>
<li><strong>服务提供商：</strong>Cloudflare（CDN 和边缘计算）、支付处理商等，仅限于提供服务所必需的数据</li>
<li><strong>法律要求：</strong>根据有效的法律程序（如法院命令、传票），我们可能被要求提供特定用户数据</li>
<li><strong>业务转让：</strong>如发生合并、收购或资产出售，用户数据可能作为业务资产的一部分转让，受让方须继续遵守本隐私政策</li>
</ul>
<div class="highlight-box">
<strong>透明度承诺：</strong>我们承诺每年发布一次安全透明度报告，披露收到的数据请求数量及处理情况。
</div>

